#!/usr/bin/env python3
"""Measures assets/painted/*.png and writes game/painted-data.js (window.HEPAINTED_DATA).
Per frame: cell size, measured opaque bbox + bottom row (the grounding baseline, per audit note 2), the feet centre
(mean x of opaque pixels in the lowest 30 rows), MANIFEST muzzle coordinates, and a coarse alpha mask (1 bit per
cell of MASK px) so raycasts (player shots + fairness LOS) hit the painted silhouette, not the transparent quad."""
import base64, json, os, sys
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); SRC = os.path.join(ROOT, 'assets', 'painted')
MASK = 8   # px per mask cell
# MANIFEST.md §3 measured muzzle / barrel / flash coordinates (px in the frame's own cell; facing as painted)
MUZ = { 'maya-aim-side': {'muzzle': [103, 224]}, 'maya-crouch-chair': {'muzzle': [139, 539]},
  'cole-bed-foot': {'muzzle': [236, 79]}, 'cole-ambulance-braced': {'muzzle': [187, 104]},
  'enemy-plain-peek': {'muzzle': [244, 149]}, 'enemy-plain-aim': {'muzzle': [398, 211]},
  'enemy-plain-fire': {'muzzle': [356, 211], 'flash': [446, 211]},
  'enemy-scrubs-aim': {'muzzle': [86, 198]}, 'enemy-scrubs-fire': {'muzzle': [162, 197], 'flash': [61, 196]} }
# Maya's push grip: measured hand centre (fingertip extreme - 18 px) in rows 320-400 of each push frame
GRIP = { 'maya-push-01': [351, 362], 'maya-push-02': [329, 350], 'maya-push-03': [328, 361], 'maya-push-04': [331, 352] }
# OPUS-INTEGRATE-WALK-COLE: the MANIFEST contact points are quarantined (Moth audit). Measured ground-contact clusters
# (Moth's audit, quoted in the tasking) — x ranges on the bottom row; they set the horizontal anchor + the contact shadow.
CONTACT = { 'enemy-plain-walk-01': [[309, 342]], 'enemy-plain-walk-02': [[350, 365]], 'enemy-plain-walk-03': [[84, 111], [385, 412]], 'enemy-plain-walk-04': [[287, 308]],
  'enemy-scrubs-walk-01': [[346, 376]], 'enemy-scrubs-walk-02': [[167, 177]], 'enemy-scrubs-walk-03': [[429, 451]], 'enemy-scrubs-walk-04': [[392, 411]] }
# braced Cole: replacement anchors (measured, Moth): bottom 717 at x~274 (front toe); hand ~(630,634); rear foot ~(145,658)
SEAT = { 'cole-ambulance-braced': {'toe': [274, 717], 'hand': [630, 634], 'rear': [145, 658]} }
AUDIT_BOTTOM = { 'enemy-plain-walk-01': 718, 'enemy-plain-walk-02': 712, 'enemy-plain-walk-03': 718, 'enemy-plain-walk-04': 714,
  'enemy-scrubs-walk-01': 718, 'enemy-scrubs-walk-02': 712, 'enemy-scrubs-walk-03': 718, 'enemy-scrubs-walk-04': 714, 'cole-ambulance-braced': 717 }
FACE = { 'enemy-plain': 1, 'enemy-scrubs': -1, 'maya-aim-side': -1, 'maya-crouch-chair': -1 }   # +1 faces/aims +X as painted
out = {}
for fn in sorted(os.listdir(SRC)):
    if not fn.endswith('.png') or fn.endswith('-sheet.png'): continue
    name = fn[:-4]; im = Image.open(os.path.join(SRC, fn)).convert('RGBA'); W, H = im.size; a = im.getchannel('A'); px = a.load()
    x0, y0, x1, y1 = a.point(lambda v: 255 if v >= 64 else 0).getbbox()   # PIL bbox is exclusive at x1/y1
    bottom = y1 - 1; xs = [x for y in range(max(0, bottom - 30), bottom + 1) for x in range(W) if px[x, y] >= 64]
    feet = round(sum(xs) / len(xs), 1) if xs else (x0 + x1) / 2
    mw, mh = (W + MASK - 1) // MASK, (H + MASK - 1) // MASK; bits = bytearray((mw * mh + 7) // 8)
    for my in range(mh):
        for mx in range(mw):
            on = False
            for y in range(my * MASK, min(H, my * MASK + MASK), 2):
                for x in range(mx * MASK, min(W, mx * MASK + MASK), 2):
                    if px[x, y] >= 128: on = True; break
                if on: break
            if on: i = my * mw + mx; bits[i >> 3] |= 1 << (i & 7)
    face = next((v for k, v in FACE.items() if name.startswith(k)), 1)
    out[name] = dict(w=W, h=H, bbox=[x0, y0, x1 - 1, bottom], bottom=bottom, feet=feet, face=face, mw=mw, mh=mh, mask=base64.b64encode(bytes(bits)).decode(), **MUZ.get(name, {}))
    if name in GRIP: out[name]['grip'] = GRIP[name]
    if name in CONTACT: out[name]['contact'] = CONTACT[name]
    if name in SEAT: out[name]['seat'] = SEAT[name]
    if name in AUDIT_BOTTOM: assert bottom == AUDIT_BOTTOM[name], (name, bottom, AUDIT_BOTTOM[name])   # audited bottoms must hold
js = ('/* GENERATED by tools/painted-data.py from assets/painted/*.png — do not edit. Measured per-frame metrics + alpha masks. */\n'
      'window.HEPAINTED_DATA = { scale: 341.6, mask: %d, frames: %s };\n' % (MASK, json.dumps(out, separators=(',', ':'))))
open(os.path.join(ROOT, 'game', 'painted-data.js'), 'w').write(js)
for k, v in out.items(): print('%-26s %dx%d bbox=%s bottom=%d feet=%s face=%d' % (k, v['w'], v['h'], v['bbox'], v['bottom'], v['feet'], v['face']))
print('bytes', len(js))
