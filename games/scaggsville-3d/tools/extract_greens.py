#!/usr/bin/env python3
"""Extract the REAL OSM green areas (woods / parks) for Scaggsville 3D.

Source: ../laurel-fulton/data/areas.json (the old game's baked OSM areas, 5 units per metre).
The frame transform to Scaggsville 3D metres (origin at Brad's house, x east, z south) is not
assumed: it is FITTED by matching every src/data.js building footprint centroid to its nearest
areas.json building centroid (median offset, reported with its residual).

Output: src/world/greens.js — polygons clipped to the 3D map extent (+ margin), simplified at
1.5 m (Douglas-Peucker), never moved. Rerunnable: python3 tools/extract_greens.py
"""
import json, math, os, statistics, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
AREAS = os.path.join(ROOT, '..', 'laurel-fulton', 'data', 'areas.json')
DATA = os.path.join(ROOT, 'src', 'data.js')
OUT = os.path.join(ROOT, 'src', 'world', 'greens.js')
UNITS_PER_M = 5.0
MARGIN = 900.0     # m beyond the kept road extent (fog far is ~700 m)
SIMPLIFY = 1.5     # m

def load_data():
    s = open(DATA).read()
    return json.loads(s[s.index('{'):s.rindex('}') + 1])

def cen_flat(f):
    xs, ys = f[0::2], f[1::2]
    return sum(xs) / len(xs), sum(ys) / len(ys)

def dp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy) or 1e-9
    imax, dmax = 0, -1
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / L
        if d > dmax: imax, dmax = i, d
    if dmax <= eps: return [a, b]
    return dp(pts[:imax + 1], eps)[:-1] + dp(pts[imax:], eps)

def area(p):
    return abs(sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p)))) / 2

def main():
    A = json.load(open(AREAS)); D = load_data()
    # --- fit the transform from building correspondences ---
    ac = [cen_flat(f) for f in A['buildings']]
    grid = {}
    for i, (x, y) in enumerate(ac): grid.setdefault((int(x // 500), int(y // 500)), []).append(i)
    bx, by = cen_flat(A['buildings'][5608])  # Brad's house (heroes: b 5608) — the frame origin
    offs = []
    for b in D['buildings']:
        p = b['pts']; cx = sum(q[0] for q in p) / len(p); cz = sum(q[1] for q in p) / len(p)
        X, Y = bx + cx * UNITS_PER_M, by + cz * UNITS_PER_M
        best = None
        for gx in range(int(X // 500) - 1, int(X // 500) + 2):
            for gy in range(int(Y // 500) - 1, int(Y // 500) + 2):
                for i in grid.get((gx, gy), []):
                    d = (ac[i][0] - X) ** 2 + (ac[i][1] - Y) ** 2
                    if best is None or d < best[0]: best = (d, i)
        if best and best[0] < (10 * UNITS_PER_M) ** 2:
            offs.append(((ac[best[1]][0] - X) / UNITS_PER_M, (ac[best[1]][1] - Y) / UNITS_PER_M))
    ox = statistics.median(o[0] for o in offs); oz = statistics.median(o[1] for o in offs)
    resid = statistics.median(math.hypot(o[0] - ox, o[1] - oz) for o in offs)
    to_m = lambda X, Y: ((X - bx) / UNITS_PER_M - ox, (Y - by) / UNITS_PER_M - oz)
    xs = [q[0] for r in D['roads'] for q in r['pts']]; zs = [q[1] for r in D['roads'] for q in r['pts']]
    x0, x1, z0, z1 = min(xs) - MARGIN, max(xs) + MARGIN, min(zs) - MARGIN, max(zs) + MARGIN
    out = []; total = 0
    for f in A['green']:
        pts = [to_m(f[i], f[i + 1]) for i in range(0, len(f), 2)]
        if max(p[0] for p in pts) < x0 or min(p[0] for p in pts) > x1 or max(p[1] for p in pts) < z0 or min(p[1] for p in pts) > z1:
            continue
        # closed ring: split at the vertex farthest from the first so neither half has a zero baseline
        k = max(range(len(pts)), key=lambda i: (pts[i][0] - pts[0][0]) ** 2 + (pts[i][1] - pts[0][1]) ** 2)
        s = dp(pts[:k + 1], SIMPLIFY)[:-1] + dp(pts[k:] + [pts[0]], SIMPLIFY)[:-1]
        if len(s) < 3 or area(s) < 150: continue
        total += area(s)
        out.append([[round(p[0], 1), round(p[1], 1)] for p in s])
    hdr = ('// Scaggsville 3D — REAL OSM green areas (woods / parks), generated by tools/extract_greens.py.\n'
           f'// Source: laurel-fulton/data/areas.json `green` ({len(A["green"])} polygons). Frame fitted from '
           f'{len(offs)} building matches: offset ({ox:.2f}, {oz:.2f}) m, median residual {resid:.2f} m.\n'
           f'// Kept: {len(out)} polygons within the map extent + {MARGIN:.0f} m, {total / 1e6:.2f} km2, '
           f'simplified at {SIMPLIFY} m, never moved.\n')
    with open(OUT, 'w') as fh:
        fh.write(hdr + 'export const GREENS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print(f'matches {len(offs)} offset ({ox:.2f},{oz:.2f}) resid {resid:.2f} m; kept {len(out)} polys {total/1e6:.2f} km2; '
          f'{os.path.getsize(OUT)/1024:.0f} KB')

if __name__ == '__main__':
    main()
